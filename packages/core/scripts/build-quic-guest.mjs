/*
 * Generates src/process/executors/node/runtime/guest/modules/quic.ts (QUIC_SRC) from the QUIC
 * transport sources in src/network/quic, entry guest-entry.ts.
 *
 * The guest runs plain JavaScript inside QuickJS, so the TypeScript modules are bundled into one IIFE
 * script. Every import of './crypto' inside src/network/quic resolves to guest-crypto.ts, which
 * reaches the host primitives through capability calls; the build fails if crypto.ts or @noble ends
 * up in the bundle.
 *
 * QUIC_SRC carries that script as a string literal and compiles it on first use: it defines the
 * bootstrap-scope function OWC_QUIC(), which compiles and runs the bundle once (passing it the
 * bootstrap helpers it needs) and returns its exports, and registers the internal built-ins
 * 'owc:internal/quic' (OWC_QUIC().API) and 'owc:internal/http3' (OWC_QUIC().loadHttp3(), the HTTP/3
 * API). A guest process that never uses QUIC only lexes the string; compiling the bundle costs about
 * 18 ms in QuickJS.
 *
 * Usage (in packages/core): node scripts/build-quic-guest.mjs [--check]
 *   --check: exit 1 when the generated file is out of date, without writing it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const quicDir = path.join(root, 'src', 'network', 'quic');
const guestCrypto = path.join(quicDir, 'guest-crypto.ts');
const outFile = path.join(root, 'src', 'process', 'executors', 'node', 'runtime', 'guest', 'modules', 'quic.ts');

const guestCryptoPlugin = {
    name: 'quic-guest-crypto',
    setup(b) {
        b.onResolve({ filter: /^\.\/crypto$/ }, (args) => {
            if (path.dirname(args.importer) !== quicDir || args.importer === guestCrypto) return undefined;
            return { path: guestCrypto };
        });
    },
};

const result = await build({
    entryPoints: [path.join(quicDir, 'guest-entry.ts')],
    bundle: true,
    format: 'iife',
    globalName: '__owcQuicModule',
    target: 'es2020',
    platform: 'neutral',
    charset: 'ascii',
    legalComments: 'none',
    write: false,
    metafile: true,
    logLevel: 'warning',
    plugins: [guestCryptoPlugin],
});

const inputs = Object.keys(result.metafile.inputs);
const forbidden = inputs.filter((input) => input.includes('@noble') || /(^|\/)crypto\.ts$/.test(input));
if (forbidden.length > 0) {
    console.error('host-only modules reached the guest bundle:', forbidden.join(', '));
    process.exit(1);
}

const bundle = result.outputFiles[0].text;
const guestScript = [
    '/* QUIC transport and HTTP/3 (generated). OWC_QUIC() compiles the bundle on first use and returns its exports. */',
    'var OWC_QUIC = (function () {',
    '  var loaded = null;',
    `  var SOURCE = ${JSON.stringify(bundle)};`,
    '  return function () {',
    "    if (loaded === null) loaded = new Function('callCap', 'OWC_TLS13', 'requireBuiltin', 'Buffer', SOURCE + '\\nreturn __owcQuicModule;')(callCap, OWC_TLS13, requireBuiltin, Buffer);",
    '    return loaded;',
    '  };',
    '})();',
    "BF['owc:internal/quic'] = function () { return OWC_QUIC().API; };",
    "BF['owc:internal/http3'] = function () { return OWC_QUIC().loadHttp3(); };",
    '',
].join('\n');
const header = [
    '/*',
    ' * GENERATED by scripts/build-quic-guest.mjs from src/network/quic (entry guest-entry.ts). Do not edit;',
    ' * edit the sources and run `node scripts/build-quic-guest.mjs`.',
    ' *',
    ' * Guest source for the QUIC version 1 transport (RFC 9000, RFC 9001, RFC 9002 subset) and HTTP/3 with',
    ' * a static-table QPACK (RFC 9114, RFC 9204). It defines the bootstrap-scope function OWC_QUIC(), which',
    ' * compiles the bundle on first use and returns its exports, and registers the internal built-ins',
    " * 'owc:internal/quic' (OWC_QUIC().API) and 'owc:internal/http3' (OWC_QUIC().loadHttp3()). The bundle",
    ' * needs the bootstrap helpers callCap, requireBuiltin, Buffer and OWC_TLS13 (TLS_ENGINE_SRC).',
    ` * Bundled modules: ${inputs.map((input) => path.basename(input)).join(', ')}.`,
    ' */',
].join('\n');
const code = guestScript;
const text = `${header}\nexport const QUIC_SRC: string = ${JSON.stringify(guestScript)};\n`;

if (process.argv.includes('--check')) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (current !== text) {
        console.error(`${path.relative(root, outFile)} is out of date`);
        process.exit(1);
    }
    console.log(`${path.relative(root, outFile)} is up to date (${code.length} bytes of guest script)`);
} else {
    fs.writeFileSync(outFile, text);
    console.log(`wrote ${path.relative(root, outFile)}: ${code.length} bytes of guest script from ${inputs.length} modules`);
}
