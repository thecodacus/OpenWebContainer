/*
 * Generates the guest modules of the Node-API shims registered in src/napi/registry.ts: for each shim,
 * src/process/executors/node/runtime/guest/modules/napi-<shim>.ts (NAPI_<SHIM>_SRC), and the list of them,
 * guest/modules/napi.ts (NAPI_SRCS), which guest/modules/index.ts appends to the module families.
 *
 * A shim is src/napi/<shim>/index.ts exporting createAddon(): object, the add-on's exports. The guest runs plain
 * JavaScript inside QuickJS, so the shim is bundled into one IIFE script, and it must be pure JavaScript: the
 * bundle targets a neutral platform, where a Node built-in does not resolve, and the build fails when the bundle
 * mentions WebAssembly or does not export createAddon.
 *
 * NAPI_<SHIM>_SRC registers the shim's add-on basenames and packages for process.dlopen (NAPI_BINARIES,
 * NAPI_PACKAGES) and the internal built-in 'owc:internal/napi/<shim>', which compiles the bundle on first use
 * and returns its exports. A guest process that never loads the add-on only lexes the string.
 *
 * Usage (in packages/core): node scripts/build-napi-guest.mjs [--check]
 *   --check: exit 1 when a generated file is out of date, missing or left over from a removed shim, without
 *   writing anything.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const napiDir = path.join(root, 'src', 'napi');
const modulesDir = path.join(root, 'src', 'process', 'executors', 'node', 'runtime', 'guest', 'modules');
const listFile = path.join(modulesDir, 'napi.ts');
const GENERATED = ' * GENERATED by scripts/build-napi-guest.mjs';

function fail(message) {
    console.error(`build-napi-guest: ${message}`);
    process.exit(1);
}

async function loadRegistry() {
    const result = await build({
        entryPoints: [path.join(napiDir, 'registry.ts')],
        absWorkingDir: root,
        bundle: true,
        format: 'esm',
        platform: 'neutral',
        write: false,
        logLevel: 'warning',
    });
    const url = 'data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].text).toString('base64');
    return (await import(url)).NAPI_SHIMS;
}

function validateEntry(shim) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(shim.name)) fail(`shim name ${JSON.stringify(shim.name)} must be lowercase letters, digits and dashes`);
    for (const binary of shim.binaries) {
        if (typeof binary !== 'string' || !binary.endsWith('.node') || binary.includes('/')) fail(`${shim.name}: binary ${JSON.stringify(binary)} must be a .node file basename`);
    }
    for (const [name, paths] of Object.entries(shim.packages)) {
        for (const relative of paths) {
            if (typeof relative !== 'string' || relative.startsWith('/') || relative.split('/').includes('..') || !relative.endsWith('.node')) {
                fail(`${shim.name}: placeholder ${JSON.stringify(relative)} of ${name} must be a .node path inside the package`);
            }
        }
    }
}

async function bundleShim(shim) {
    const shimDir = path.join(napiDir, shim.name);
    const entry = path.join(shimDir, 'index.ts');
    if (!fs.existsSync(entry)) fail(`${shim.name}: ${path.relative(root, entry)} does not exist`);
    const result = await build({
        entryPoints: [entry],
        absWorkingDir: root,
        bundle: true,
        format: 'iife',
        globalName: '__owcNapiShim',
        target: 'es2020',
        platform: 'neutral',
        charset: 'ascii',
        minify: true,
        legalComments: 'none',
        write: false,
        metafile: true,
        logLevel: 'warning',
    });
    const bundle = result.outputFiles[0].text;
    if (bundle.includes('WebAssembly')) fail(`${shim.name}: the bundle uses WebAssembly, which the guest does not have`);
    const exported = new Function(bundle + '\nreturn __owcNapiShim;')();
    if (typeof exported.createAddon !== 'function') fail(`${shim.name}: index.ts does not export createAddon()`);
    const prefix = path.relative(root, shimDir) + '/';
    const inputs = Object.keys(result.metafile.inputs).map((input) => (input.startsWith(prefix) ? input.slice(prefix.length) : input));
    return { bundle, inputs };
}

function moduleText(shim, constName, bundle, inputs) {
    const key = `owc:internal/napi/${shim.name}`;
    const packages = Object.keys(shim.packages);
    const guestScript = [
        `/* Node-API shim ${shim.name} (generated). process.dlopen serves its add-ons from '${key}', which compiles the bundle on first use. */`,
        ...shim.binaries.map((binary) => `NAPI_BINARIES[${JSON.stringify(binary)}] = ${JSON.stringify(shim.name)};`),
        ...packages.map((name) => `NAPI_PACKAGES[${JSON.stringify(name)}] = ${JSON.stringify(shim.name)};`),
        `BF[${JSON.stringify(key)}] = function () {`,
        `  return new Function(${JSON.stringify(bundle)} + '\\nreturn __owcNapiShim;')();`,
        '};',
        '',
    ].join('\n');
    const served = [...shim.binaries, ...packages.map((name) => `any add-on in package ${name}`)].join('; ');
    const header = [
        '/*',
        `${GENERATED} from src/napi/${shim.name} (entry index.ts). Do not edit;`,
        ' * edit the shim or src/napi/registry.ts and run `node scripts/build-napi-guest.mjs`.',
        ' *',
        ` * Guest source for the Node-API shim '${shim.name}'. It registers the add-on files process.dlopen serves from`,
        ` * the shim (${served}) and the internal built-in '${key}', which compiles`,
        ' * the bundled shim on first use and returns its exports (createAddon).',
        ` * Bundled modules: ${inputs.join(', ')}.`,
        ' */',
    ].join('\n');
    return { text: `${header}\nexport const ${constName}: string = ${JSON.stringify(guestScript)};\n`, scriptBytes: guestScript.length };
}

function listText(entries) {
    return [
        '/*',
        `${GENERATED} from src/napi/registry.ts. Do not edit;`,
        ' * register a shim in src/napi/registry.ts and run `node scripts/build-napi-guest.mjs`.',
        ' *',
        ' * The guest sources of the Node-API shims, in registry order. guest/modules/index.ts appends them to the',
        ' * module families; each registers its add-ons for process.dlopen and its owc:internal/napi/<shim> built-in.',
        ' */',
        ...entries.map(({ constName, base }) => `import { ${constName} } from './${base}';`),
        ...(entries.length > 0 ? [''] : []),
        `export const NAPI_SRCS: string[] = [${entries.map(({ constName }) => constName).join(', ')}];`,
        '',
    ].join('\n');
}

const shims = await loadRegistry();
const expected = new Map();
const entries = [];
for (const shim of shims) {
    validateEntry(shim);
    const constName = `NAPI_${shim.name.toUpperCase().replace(/-/g, '_')}_SRC`;
    const base = `napi-${shim.name}`;
    const { bundle, inputs } = await bundleShim(shim);
    const { text, scriptBytes } = moduleText(shim, constName, bundle, inputs);
    expected.set(path.join(modulesDir, `${base}.ts`), { text, note: `${scriptBytes} bytes of guest script from ${inputs.length} modules` });
    entries.push({ constName, base });
}
expected.set(listFile, { text: listText(entries), note: `${entries.length} shim(s)` });
const leftovers = fs.readdirSync(modulesDir)
    .filter((name) => /^napi-.+\.ts$/.test(name))
    .map((name) => path.join(modulesDir, name))
    .filter((file) => !expected.has(file));

if (process.argv.includes('--check')) {
    let stale = false;
    for (const [file, { text, note }] of expected) {
        const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
        if (current !== text) {
            console.error(`${path.relative(root, file)} is out of date`);
            stale = true;
        } else {
            console.log(`${path.relative(root, file)} is up to date (${note})`);
        }
    }
    for (const file of leftovers) {
        console.error(`${path.relative(root, file)} belongs to no registered shim`);
        stale = true;
    }
    if (stale) process.exit(1);
} else {
    for (const file of leftovers) {
        if (!fs.readFileSync(file, 'utf8').includes(GENERATED)) fail(`${path.relative(root, file)} is not generated; remove it by hand`);
        fs.rmSync(file);
        console.log(`removed ${path.relative(root, file)}`);
    }
    for (const [file, { text, note }] of expected) {
        fs.writeFileSync(file, text);
        console.log(`wrote ${path.relative(root, file)}: ${note}`);
    }
}
